create function public.end_shift()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_vehicle uuid;
begin
  update public.vehicle_live set online = false
  where driver_id = auth.uid() and online
  returning vehicle_id into v_vehicle;

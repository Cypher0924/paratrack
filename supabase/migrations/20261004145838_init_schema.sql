returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_command text;
begin
  select j.command into v_command from cron.job j where j.jobname = p_name;
  if v_command is null then
    raise exception 'no_such_job';
  end if;
  execute v_command;
end;
$$;


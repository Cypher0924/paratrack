create function public.check_trip_stops()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if exists (
    select 1
    from unnest(array[new.board_stop_id, new.alight_stop_id]) as s(stop_id)
    where s.stop_id is not null
      and not exists (
        select 1
        from public.route_stops rs
        join public.vehicles v on v.route_id = rs.route_id
        where v.id = new.vehicle_id and rs.stop_id = s.stop_id
      )
  ) then
    raise exception 'stop_not_on_route';
  end if;
  return new;
end;
$$;

